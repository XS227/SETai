// Black & White Universe, chapter 05 «Entanglement»: the scenes the shared engine (bwu-scene.js) renders.
window.BWU_SCENES = [
'vec3 bg(vec2 p, float t){ return vec3(.01)+vec3(.03)*fbm(p*2.2+vec2(t*.02,-t*.015))*(1.-smoothstep(0.,1.2,length(p)))+vec3(stars(p*55.,.03))*.35; }',
'vec3 WARM=vec3(1.,.62,.34);',
'float pt(vec2 p, vec2 c, float k){ vec2 d=p-c; return k/(dot(d,d)+k); }',

// I: a voice made of thousands of souls, one thought echoing through every other mind
'vec3 sVoices(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.7; float r=length(p);',
'  vec2 g=floor(p*18.); vec2 o=vec2(h21(g),h21(g+3.7))*.7+.15; vec2 wp=(g+o)/18.;',
'  float has=step(.35,h21(g+9.))*(1.-smoothstep(.25,.45,length(wp)));',
'  float front=fract(t*.18)*.6, dist=length(wp);',
'  float hit=exp(-sq((dist-front)*25.))*smoothstep(.0,.3,m+.2);',
'  float d=length(p-wp);',
'  c+=vec3(1.)*glowLine(d,(1.2+2.*hit)*PX)*has*(.25+.9*hit);',
'  c+=vec3(.6)*glowLine(r-front,1.4*PX)*(1.-smoothstep(.3,.6,front))*(.3+.5*m);',
'  c+=vec3(1.)*pt(p,vec2(0.),.00004);',
'  return c; }',

// II: two particles that once shared a state spin as one, however far they drift
'vec3 sPair(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float sep=mix(.015,.34,smoothstep(0.,.85,m));',
'  vec2 A=vec2(-sep,0.), B=vec2(sep,0.);',
'  float flip=step(.5,fract(t*.25)), ang=t*1.6;',
'  for(int k=0;k<2;k++){ vec2 C=k==0?A:B; float sgn=k==0?1.:-1.;',
'    vec2 ax=vec2(cos(ang*sgn),sin(ang*sgn))*.045;',
'    c+=vec3(.95)*glowLine(sdSeg(p,C-ax,C+ax),1.3*PX)+vec3(1.)*pt(p,C,.00005)+vec3(.5)*exp(-length(p-C)*40.)*.3;',
'    c+=vec3(.6)*glowLine(length((p-C)*vec2(1.,2.6))-.06,1.2*PX)*(.5+.5*flip); }',
'  float th=glowLine(p.y+.004*sin(p.x*40.-t*3.),1.*PX)*step(abs(p.x),sep)*.35*smoothstep(.1,.5,m);',
'  c+=vec3(.8)*th;',
'  return c; }',

// III: we were all one soul, separated to recognize each other again
'vec3 sOneSoul(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float sp=smoothstep(.05,.7,m), f=0.;',
'  for(int k=0;k<6;k++){ float an=float(k)*1.0472+t*.05; vec2 P=vec2(cos(an),sin(an))*.24*sp; f+=.0042/dot(p-P,p-P); }',
'  float iso=glowLine(f-1.,.18), body=smoothstep(.9,1.4,f);',
'  c+=vec3(.95)*iso*.9+vec3(.18)*body;',
'  float rec=smoothstep(.75,1.,m);',
'  for(int k=0;k<6;k++){ float an=float(k)*1.0472+t*.05; vec2 P=vec2(cos(an),sin(an))*.24*sp, P2=vec2(cos(an+1.0472),sin(an+1.0472))*.24*sp;',
'    c+=vec3(.7)*glowLine(sdSeg(p,P,P2),1.*PX)*rec; c+=vec3(1.)*pt(p,P,.00003); }',
'  return c; }',

// IV: if you love, another light turns on somewhere; if you lie, a wave of darkness travels
'vec3 sHearts(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.6;',
'  vec2 g=floor(p*20.); vec2 o=vec2(h21(g),h21(g+3.7))*.7+.15; vec2 wp=(g+o)/20.;',
'  float has=step(.3,h21(g+9.))*(1.-smoothstep(.28,.46,length(wp)));',
'  float lit=step(h21(g+2.),smoothstep(.0,.55,m))*step(.55,h21(g+5.));',
'  float dark=smoothstep(.55,.95,m), wave=(m-.55)/.4*1.1-.45;',
'  float shadow=dark*smoothstep(wave-.12,wave,wp.x)*(1.-smoothstep(wave,wave+.25,wp.x));',
'  float on=(.18+.82*lit*(.7+.3*sin(t*2.+h21(g)*6.)))*(1.-shadow*.9);',
'  c+=vec3(1.)*glowLine(length(p-wp),(1.2+1.4*lit)*PX)*has*on;',
'  c+=mix(vec3(1.),WARM,.5)*exp(-length(p-vec2(-.3,.0))*25.)*.35*(1.-dark);',
'  c*=1.-.6*dark*exp(-sq((p.x-wave)*6.));',
'  return c; }',

// V: woven from intentions, emotions and frequencies; every prayer a vibration along the threads
'vec3 sWoven(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.6; float env=1.-smoothstep(.22,.5,length(p));',
'  float k=22.; vec2 q=p*k; vec2 id=floor(q), f=fract(q)-.5;',
'  float over=mod(id.x+id.y,2.);',
'  float hx=glowLine(f.y+.08*sin(q.x*PI),.09), hy=glowLine(f.x+.08*sin(q.y*PI),.09);',
'  float pulseX=exp(-sq(fract(p.x*1.4-t*.25+h21(vec2(id.y,1.)))-.5)*30.), pulseY=exp(-sq(fract(p.y*1.4-t*.21+h21(vec2(id.x,2.)))-.5)*30.);',
'  float a=mix(.35,.75,over)*hx*(.35+.65*pulseX*m), b=mix(.75,.35,over)*hy*(.35+.65*pulseY*m);',
'  c+=vec3(.9)*max(a,b)*env;',
'  return c; }',

// VI: spooky action at a distance, two far points answering each other at once; at the end the thread turns warm
'vec3 sSpooky(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  vec2 A=vec2(-.33,.05), B=vec2(.33,-.05);',
'  float ph=fract(t*.3), flash=exp(-ph*8.);',
'  for(int k=0;k<2;k++){ vec2 C=k==0?A:B; float r=length(p-C);',
'    c+=vec3(1.)*pt(p,C,.00005)*(1.+flash*2.)+vec3(.8)*glowLine(r-ph*.12,1.3*PX)*(1.-ph); }',
'  float love=smoothstep(.45,.9,m);',
'  float d=sdSeg(p,A,B)+.006*sin(length(p-A)*60.-t*4.)*(1.-love);',
'  c+=mix(vec3(.5),WARM,love)*glowLine(d,mix(.8,1.5,love)*PX)*(.25+.75*m)+WARM*glowLine(d,8.*PX)*love*.2;',
'  return c; }',

// VII: it is Love that keeps the universe spinning
'vec3 sSpin(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.6;',
'  vec2 q=rot(t*mix(.05,.35,m))*p; q.y*=1.5; float r=length(q), a=atan(q.y,q.x);',
'  float arms=.5+.5*cos(2.*(a-log(r+.001)*2.6));',
'  float g=exp(-r*4.5)*(.25+.75*arms*arms)*(.55+.6*fbm(q*8.))+stars(q*70.,.06)*.5*exp(-r*2.);',
'  c+=vec3(g)*1.1;',
'  c+=mix(vec3(1.),WARM,.6)*exp(-r*28.)*(.6+.4*sin(t*2.6))*(.4+.6*m);',
'  return c; }',

// VIII: reborn with every breath; love expands it, hate deepens the black holes, and at last it rests
'vec3 sBreath(vec2 p, float t, float m){',
'  vec3 c=bg(p,t); float r=length(p);',
'  float settle=smoothstep(.82,1.,m);',
'  float br=.5+.5*sin(t*1.1); br=mix(br,.5,settle);',
'  float R=mix(.14,.22,smoothstep(0.,.45,m))+.035*br*(1.-settle);',
'  float hate=smoothstep(.45,.7,m)*(1.-settle);',
'  float holes=0.;',
'  for(int k=0;k<4;k++){ float fk=float(k); vec2 hc=vec2(cos(fk*1.7+1.),sin(fk*2.3))*R*.6; holes=max(holes,1.-smoothstep(.0,.035*hate+.001,length(p-hc))); }',
'  float sphere=1.-smoothstep(R-.003,R,r);',
'  vec3 col=vec3(.12+.55*exp(-r/R*1.6))*(.8+.2*fbm(p*12.+t*.1));',
'  col*=1.-holes*.95;',
'  c=mix(c,col,sphere);',
'  c+=vec3(.9)*glowLine(r-R,1.4*PX)+vec3(.35)*glowLine(r-R,10.*PX)*(.15+.25*br);',
'  for(int k=0;k<4;k++){ float fk=float(k); vec2 hc=vec2(cos(fk*1.7+1.),sin(fk*2.3))*R*.6; c+=vec3(.7)*glowLine(length(p-hc)-.035*hate,1.*PX)*hate; }',
'  c+=vec3(.5)*glowLine(r-R*1.25,1.*PX)*settle*.6;',
'  return c; }',

// IX: every time you look into another's eyes, you see a version of yourself
'float eyeShape(vec2 q, float W, float H){ return abs(q.y)-H*(1.-sq(q.x/W)); }',
'vec3 eyeAt(vec2 q, float t, float lvl){',
'  float lid=eyeShape(q,.15,.07); float inside=(1.-smoothstep(-.002,.002,lid))*step(abs(q.x),.15);',
'  float r=length(q), iris=(1.-smoothstep(.042,.045,r)), pupil=1.-smoothstep(.016,.018,r);',
'  float a=atan(q.y,q.x); float tex=.35+.65*fbm(vec2(a*12.,r*40.));',
'  vec3 c=vec3(.0); c=mix(c,vec3(.12),inside); c=mix(c,vec3(.55)*tex,iris*inside); c=mix(c,vec3(.0),pupil*inside);',
'  c+=vec3(.85)*glowLine(lid,1.2*PX/lvl)*step(abs(q.x),.15);',
'  c+=vec3(1.)*exp(-length(q-vec2(-.012,.014))*400.)*inside;',
'  return c; }',
'vec3 sEyes(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.5; p/=1.4;',
'  float near=mix(.24,.18,smoothstep(0.,.8,m));',
'  vec2 L=p-vec2(-near,0.), R=p-vec2(near,0.);',
'  c+=eyeAt(L,t,1.)+eyeAt(R,t,1.);',
'  float deep=smoothstep(.3,.9,m);',
'  for(int k=0;k<2;k++){ vec2 C=k==0?L:R; vec2 q=C/.17; if(length(C)<.017){ c+=eyeAt(q,t,6.)*deep*.9; } }',
'  return c; }',

// X: we are different ways of seeing the same consciousness
'vec3 sOne(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.6; float r=length(p);',
'  float n=floor(mix(5.,26.,smoothstep(0.,.8,m)));',
'  for(int k=0;k<26;k++){ float fk=float(k); if(fk>=n) break;',
'    float ring=fk<8.?.16:(fk<17.?.27:.37), an=fk*2.39996+t*.04*(ring>.2?-1.:1.);',
'    vec2 C=vec2(cos(an),sin(an))*ring; vec2 d=p-C; float rr=.026;',
'    float disc=1.-smoothstep(rr-.002,rr,length(d));',
'    vec2 toC=normalize(-C); float lit=clamp(dot(normalize(d+1e-4),toC)*.8+.25,0.,1.);',
'    c=mix(c,vec3(.05)+vec3(.85)*lit*lit,disc); c+=vec3(.5)*glowLine(length(d)-rr,1.*PX); }',
'  c+=mix(vec3(1.),WARM,.25)*(pt(p,vec2(0.),.00008)+exp(-r*16.)*.25);',
'  return c; }',

'vec3 scene(float id, vec2 p, float t, float m){',
'  if(id<.5) return sVoices(p,t,m);',
'  if(id<1.5) return sPair(p,t,m);',
'  if(id<2.5) return sOneSoul(p,t,m);',
'  if(id<3.5) return sHearts(p,t,m);',
'  if(id<4.5) return sWoven(p,t,m);',
'  if(id<5.5) return sSpooky(p,t,m);',
'  if(id<6.5) return sSpin(p,t,m);',
'  if(id<7.5) return sBreath(p,t,m);',
'  if(id<8.5) return sEyes(p,t,m);',
'  return sOne(p,t,m); }'
].join('\n');
