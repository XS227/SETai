// Black & White Universe, chapter 02 «The Geometry of Love»: the scenes the shared engine (bwu-scene.js) renders.
window.BWU_SCENES = [
'vec3 bg(vec2 p, float t){ return vec3(.012)+vec3(.035)*fbm(p*2.2+vec2(t*.02,-t*.015))*(1.-smoothstep(0.,1.2,length(p)))+vec3(stars(p*55.,.03))*.35; }',
'float PHI=1.6180339;',

// I: the number that sings, a particle tracing a 3:2 melody, and at the end a heartbeat: Love
'vec2 liss(float s, float t){ return vec2(.3*sin(3.*s+.6), .24*sin(2.*s)); }',
'vec3 sMelody(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float head=t*.55, dmin=9., trail=0.;',
'  vec2 prev=liss(head-6.2832,t);',
'  for(int i=1;i<=90;i++){ float s=head-6.2832+float(i)*6.2832/90.; vec2 q=liss(s,t);',
'    float d=sdSeg(p,prev,q); float w=float(i)/90.; dmin=min(dmin,d); trail=max(trail,glowLine(d,1.4*PX)*pow(w,3.)); prev=q; }',
'  c+=vec3(.16)*glowLine(dmin,1.2*PX)+vec3(.95)*trail*(.35+.65*smoothstep(0.,.3,m));',
'  vec2 hp=liss(head,t); c+=vec3(.00006/(dot(p-hp,p-hp)+.00006));',
'  float beat=pow(max(0.,sin(t*3.6)),24.)+.6*pow(max(0.,sin(t*3.6-.7)),24.);',
'  float love=smoothstep(.65,.95,m);',
'  c+=mix(vec3(1.),vec3(1.,.55,.3),.5)*exp(-length(p)*14.)*(.15+.85*beat)*love*.9;',
'  return c; }',

// II: the golden ratio, squares cut away one by one and the spiral drawn through them
'vec3 sGolden(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  p=rot(.15*sin(t*.1))*p/.42; float px=PX/.42;',
'  vec2 o=vec2(-PHI*.5,-.5), sz=vec2(PHI,1.);',
'  float shown=m*11.;',
'  for(int i=0;i<11;i++){',
'    float fi=float(i), a=clamp(shown-fi,0.,1.); if(a<=0.) break;',
'    float s=min(sz.x,sz.y); vec2 lo, hi, ce; int d=int(mod(fi,4.));',
'    if(d==0){ lo=o; hi=o+vec2(s); ce=vec2(o.x+s,o.y); o.x+=s; sz.x-=s; }',
'    else if(d==1){ lo=vec2(o.x,o.y+sz.y-s); hi=lo+vec2(s); ce=lo; sz.y-=s; }',
'    else if(d==2){ lo=vec2(o.x+sz.x-s,o.y); hi=lo+vec2(s); ce=vec2(lo.x,hi.y); sz.x-=s; }',
'    else { lo=o; hi=o+vec2(s); ce=vec2(hi.x,hi.y); o.y+=s; sz.y-=s; }',
'    vec2 q=abs(p-(lo+hi)*.5)-(hi-lo)*.5; float box=abs(max(q.x,q.y));',
'    c+=vec3(.32)*glowLine(box,1.1*px)*a;',
'    float inside=step(lo.x-.001,p.x)*step(p.x,hi.x+.001)*step(lo.y-.001,p.y)*step(p.y,hi.y+.001);',
'    c+=vec3(1.)*glowLine(abs(length(p-ce)-s),1.6*px)*inside*a;',
'  }',
'  c+=vec3(.9,.85,.75)*exp(-length(p-vec2(.3,.1))*6.)*.12*smoothstep(.85,1.,m);',
'  return c; }',

// III: all existence is music, two sources whose waves interfere around a warm heart
'vec3 sMusic(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float sep=mix(.06,.16,m); vec2 a=vec2(-sep,0.), b=vec2(sep,0.);',
'  float k=mix(55.,95.,m), r1=length(p-a), r2=length(p-b);',
'  float w=sin(r1*k-t*3.)/(1.+r1*6.)+sin(r2*k-t*3.)/(1.+r2*6.);',
'  float env=1.-smoothstep(.15,.65,length(p));',
'  c+=vec3(.75)*pow(abs(w)*.55,3.)*env;',
'  c+=vec3(.0001/(r1*r1+.0001)+.0001/(r2*r2+.0001))*.6;',
'  c+=vec3(1.,.6,.35)*exp(-length(p)*30.)*(.4+.3*sin(t*2.))*smoothstep(.2,.7,m)*.6;',
'  return c; }',

// IV: we are the strings, first too tight, then too loose, then in balance
'vec3 sStrings(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float tight=1.-smoothstep(.28,.4,m), loose=smoothstep(.28,.4,m)*(1.-smoothstep(.62,.74,m)), bal=smoothstep(.62,.74,m);',
'  float L=.36, x=p.x/L;',
'  for(int i=0;i<5;i++){',
'    float fi=float(i), y0=(fi-2.)*.075;',
'    float env=sin(clamp((x+1.)*.5,0.,1.)*PI);',
'    float yT=.002*sin(x*40.+t*30.+fi)*env;',
'    float yL=-.035*env*env+.045*(fbm(vec2(x*2.+fi*3.,t*.6))-.5)*env;',
'    float n=fi+1.;',
'    float yB=.022*sin((x+1.)*.5*n*PI)*cos(t*(2.+n*.7));',
'    float y=y0+tight*yT+loose*yL+bal*yB;',
'    float d=abs(p.y-y)+(1.-step(abs(x),1.))*9.;',
'    float bright=tight*.25+loose*.55+bal*1.;',
'    c+=vec3(.95)*glowLine(d,mix(1.,1.6,bal)*PX)*bright+vec3(.5)*glowLine(d,9.*PX)*bal*.18;',
'    c+=vec3(.7)*glowLine(length(p-vec2(-L,y0)),2.5*PX)+vec3(.7)*glowLine(length(p-vec2(L,y0)),2.5*PX);',
'  }',
'  return c; }',

// V: wave and point, single dots landing one by one until the interference pattern appears
'vec3 sWave(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.7;',
'  float bx=-.2, sx=.24, s1=.045;',
'  float slit=step(s1-.012,abs(p.y))*(1.-step(s1+.012,abs(p.y)));',
'  c+=vec3(.55)*glowLine(p.x-bx,1.2*PX)*(1.-slit)*step(abs(p.y),.32);',
'  if(p.x<bx) c+=vec3(.12)*pow(.5+.5*sin(p.x*70.-t*4.),6.)*step(abs(p.y),.3)*(1.-smoothstep(.1,.3,abs(p.y)));',
'  if(p.x>bx&&p.x<sx){ float r1=length(p-vec2(bx,s1)), r2=length(p-vec2(bx,-s1));',
'    float w=sin(r1*70.-t*4.)+sin(r2*70.-t*4.); c+=vec3(.2)*w*w*.25*exp(-(p.x-bx)*3.); }',
'  c+=vec3(.4)*glowLine(p.x-sx,1.*PX)*step(abs(p.y),.32);',
'  if(p.x>sx&&p.x<sx+.11&&abs(p.y)<.32){',
'    vec2 g=floor(p*260.); float h=h21(g);',
'    float P=pow(cos(p.y*30.),2.)*exp(-p.y*p.y*14.);',
'    float lit=step(h,m*1.15*P)*step(.55,h21(g+7.));',
'    float age=fract(h*13.+t*.05);',
'    c+=vec3(.95)*lit*(.6+.4*age);',
'  }',
'  return c; }',

// VI: tension between opposites, a white and a black pole; disorder settles into its hidden order
'vec3 sOpposites(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  vec2 q=p+(vec2(fbm(p*5.+t*.1),fbm(p*5.-t*.1+4.))-.5)*.12*(1.-m);',
'  vec2 A=vec2(-.16,0.), B=vec2(.16,0.);',
'  float psi=atan(q.y-A.y,q.x-A.x)-atan(q.y-B.y,q.x-B.x);',
'  float f=abs(fract(psi/6.2832*18.)-.5);',
'  float lines=1.-smoothstep(.0,.08,f);',
'  float phi=log(length(q-A)/length(q-B));',
'  float flow=.55+.45*sin(phi*10.-t*2.);',
'  float env=1.-smoothstep(.2,.7,length(p));',
'  c+=vec3(.7)*lines*flow*env*(.35+.45*m);',
'  float ra=length(p-A), rb=length(p-B);',
'  c+=vec3(.00025/(ra*ra+.0003))+vec3(.5)*exp(-ra*30.)*.4;',
'  float disc=1.-smoothstep(.028,.031,rb); c*=1.-disc; c+=vec3(.9)*glowLine(rb-.03,1.4*PX);',
'  return c; }',

// VII: the bridge, an eight-fold Eastern star pattern and a Western graph joined by an arc of light
'vec3 sBridge(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float env=1.-smoothstep(.25,.75,length(p));',
'  vec2 q=fract(p*4.5+vec2(t*.01,0.))-.5; vec2 q2=rot(PI*.25)*q;',
'  float d1=max(abs(q.x),abs(q.y))-.3, d2=max(abs(q2.x),abs(q2.y))-.3;',
'  float east=glowLine(min(abs(d1),abs(d2)),1.3*PX*4.5)*.6+glowLine(abs(length(q)-.13),1.*PX*4.5)*.25;',
'  vec2 gq=abs(fract(p*10.)-.5); float grid=glowLine(min(gq.x,gq.y),.8*PX*10.)*.18;',
'  float curve=glowLine(p.y+.1-.08*sin(p.x*14.+t*.6),1.4*PX)*.9+glowLine(p.y+.1,.8*PX)*.3;',
'  float west=grid+curve*step(0.,p.x);',
'  float side=smoothstep(-.06,.06,p.x);',
'  c+=vec3(.85)*mix(east,west,side)*env;',
'  float ax=clamp(p.x/.36,-1.,1.), ay=-.12+.3*(1.-ax*ax);',
'  float reach=smoothstep(.05,.9,m), drawn=step(abs(p.x),.36)*step(1.-reach,abs(ax));',
'  c+=vec3(1.)*glowLine(p.y-ay,1.6*PX)*drawn+vec3(.6)*glowLine(p.y-ay,10.*PX)*drawn*.15;',
'  c+=vec3(1.)*exp(-length(p-vec2(0.,.18))*40.)*smoothstep(.85,1.,m);',
'  return c; }',

// VIII: the prism, the chapter\'s only colours: white light opens into a spectrum and closes into white again
'float cross2(vec2 a, vec2 b){ return a.x*b.y-a.y*b.x; }',
'float triIn(vec2 p, vec2 a, vec2 b, vec2 c){ float s1=cross2(b-a,p-a), s2=cross2(c-b,p-b), s3=cross2(a-c,p-c); return step(0.,s1)*step(0.,s2)*step(0.,s3); }',
'vec3 spec(float x){ return clamp(vec3(abs(x*6.-3.)-1.,2.-abs(x*6.-2.),2.-abs(x*6.-4.)),0.,1.); }',
'vec3 sPrism(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  vec2 v0=vec2(-.13,-.1), v1=vec2(.13,-.1), v2=vec2(0.,.125);',
'  float e=min(min(sdSeg(p,v0,v1),sdSeg(p,v1,v2)),sdSeg(p,v2,v0));',
'  vec2 E=vec2(-.07,.005), X=vec2(.07,-.005);',
'  c+=vec3(.95)*glowLine(sdSeg(p,vec2(-.7,.09),E),1.6*PX)+vec3(.4)*glowLine(sdSeg(p,vec2(-.7,.09),E),8.*PX)*.2;',
'  c+=vec3(.8)*glowLine(sdSeg(p,E,X),2.*PX);',
'  float open=smoothstep(.08,.35,m)*(1.-smoothstep(.62,.92,m));',
'  float spread=.32*open+.012;',
'  vec2 d=p-X; float a=atan(d.y,d.x), a0=-.06, u=(a0-a)/spread;',
'  float fan=smoothstep(-.06,0.,u)*(1.-smoothstep(1.,1.06,u))*step(0.,d.x);',
'  vec3 col=mix(vec3(1.),spec(clamp(u,0.,1.)*.8),.6*smoothstep(.02,.15,spread));',
'  c+=col*fan*(.75*exp(-length(d)*1.6))*(.4+.6*smoothstep(0.,.2,m));',
'  float back=smoothstep(.6,.92,m); vec2 dir=vec2(cos(a0-.006),sin(a0-.006));',
'  c+=vec3(1.)*glowLine(sdSeg(p,X,X+dir*.8),1.8*PX)*back+vec3(.5)*glowLine(sdSeg(p,X,X+dir*.8),9.*PX)*back*.2;',
'  float inside=triIn(p,v0,v1,v2);',
'  c+=vec3(.05)*inside+vec3(.85)*glowLine(e,1.3*PX)+vec3(.5)*glowLine(e,7.*PX)*.12;',
'  return c; }',

// IX: every line searches for a circle, a straight line bending until its ends meet
'vec3 sCircle(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float R=.2, L=6.2832*R;',
'  float k=mix(.15,1./R,smoothstep(.05,.85,m)*smoothstep(.05,.85,m)), rho=1./k;',
'  vec2 ce=vec2(0.,-R+rho); vec2 d=p-ce;',
'  float half_=min(L*.5/rho,PI), ang=atan(d.x,-d.y);',
'  vec2 e1=ce+rho*vec2(sin(half_),-cos(half_)), e2=ce+rho*vec2(-sin(half_),-cos(half_));',
'  float dist=abs(ang)<=half_ ? abs(length(d)-rho) : min(length(p-e1),length(p-e2));',
'  c+=vec3(1.)*glowLine(dist,1.7*PX)+vec3(.5)*glowLine(dist,10.*PX)*.12;',
'  float closed=smoothstep(.82,.95,m);',
'  c+=vec3(.00004/(dot(p-e1,p-e1)+.00004))*(1.-closed*.5)+vec3(.00004/(dot(p-e2,p-e2)+.00004))*(1.-closed*.5);',
'  c+=vec3(1.)*exp(-length(p-vec2(0.,R))*60.)*closed+vec3(.6)*glowLine(dist,18.*PX)*closed*.15;',
'  c+=vec3(.00005/(dot(p,p)+.00005))*closed;',
'  return c; }',

// X: numbers sing and love makes them dance, the times-table circle settling into a heart (a cardioid)
'vec3 sDance(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float R=.26, N=72.;',
'  float k=1.+smoothstep(0.,.7,m)+.04*sin(t*.5);',
'  float dmin=9.;',
'  for(int i=0;i<72;i++){ float fi=float(i);',
'    float a1=fi/N*6.2832+PI*.5, a2=mod(fi*k,N)/N*6.2832+PI*.5;',
'    dmin=min(dmin,sdSeg(p,R*vec2(cos(a1),sin(a1)),R*vec2(cos(a2),sin(a2)))); }',
'  float heart=smoothstep(.6,.9,m);',
'  c+=mix(vec3(.85),vec3(1.,.82,.7),heart*.6)*glowLine(dmin,1.1*PX)*.55;',
'  float r=length(p); c+=vec3(.6)*glowLine(r-R,1.2*PX);',
'  float a=atan(p.y,p.x); float dots=glowLine(abs(fract(a/6.2832*72.)-.5)/72.*6.2832*R,1.6*PX)*glowLine(r-R,2.*PX);',
'  c+=vec3(.9)*dots*(.6+.4*sin(a*12.+t*3.));',
'  return c; }',

'vec3 scene(float id, vec2 p, float t, float m){',
'  if(id<.5) return sMelody(p,t,m);',
'  if(id<1.5) return sGolden(p,t,m);',
'  if(id<2.5) return sMusic(p,t,m);',
'  if(id<3.5) return sStrings(p,t,m);',
'  if(id<4.5) return sWave(p,t,m);',
'  if(id<5.5) return sOpposites(p,t,m);',
'  if(id<6.5) return sBridge(p,t,m);',
'  if(id<7.5) return sPrism(p,t,m);',
'  if(id<8.5) return sCircle(p,t,m);',
'  return sDance(p,t,m); }'
].join('\n');
