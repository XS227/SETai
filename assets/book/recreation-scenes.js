// IX: each mountain was always part of one invisible song
'vec3 sSong(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float h=-.3+max(0.,.16-abs(fract((p.x+.5)*2.5)-.5)*.6)*1.4+.03*fbm(vec2(p.x*9.,2.));',
'  float mt=step(p.y,h)*step(-.3,p.y)*step(abs(p.x),.5);',
'  c=mix(c,vec3(.035)+vec3(.05)*fbm(p*12.),mt);',
'  c+=vec3(.55)*glowLine(p.y-h,1.2*PX)*step(abs(p.x),.5)*step(-.29,h);',
'  float song=-.1+.06*sin(p.x*15.7+t*1.5)*sin(t*.7+1.)+.02*sin(p.x*31.4-t*2.);',
'  float on=smoothstep(.1,.6,m);',
'  float reach=step(p.x,mix(-.5,.5,smoothstep(.05,.7,m)));',
'  c+=vec3(.95)*glowLine(p.y-song,1.3*PX)*on*reach*step(abs(p.x),.5)+vec3(.4)*glowLine(p.y-song,8.*PX)*on*reach*step(abs(p.x),.5)*.15;',
'  for(int k=0;k<5;k++){ float cx=-.4+float(k)*.2; vec2 top=vec2(cx,-.3+.16*1.4*.98);',
'    c+=vec3(.8)*glowLine(length(p-top)-.018,1.*PX)*smoothstep(.6,.9,m); }',
'  return c; }',

// X: will, thought and love in motion; a new trinity, the rhythm of becoming
'vec3 sRhythm(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float dm=9., trail=0.;',
'  for(int k=0;k<3;k++){ float fk=float(k);',
'    for(int i=0;i<24;i++){ float s=t*.6+fk*2.0944-float(i)*.04;',
'      vec2 q=.3*vec2(sin(s)+2.*sin(2.*s),cos(s)-2.*cos(2.*s))/3.;',
'      float d=length(p-q); trail+=exp(-d*d/(sq(1.6*PX)))*(1.-float(i)/24.)*.5; }',
'    float s0=t*.6+fk*2.0944; vec2 h=.3*vec2(sin(s0)+2.*sin(2.*s0),cos(s0)-2.*cos(2.*s0))/3.;',
'    c+=mix(vec3(1.),WARM,fk==2.?.6:0.)*pt(p,h,.00004); }',
'  c+=vec3(.9)*min(trail,1.)*(.3+.7*m);',
'  float born=smoothstep(.6,1.,m);',
'  c+=vec3(.5)*glowLine(length(p)-.04*born,1.2*PX)*born+vec3(.12)*exp(-length(p)*20.)*born;',
'  return c; }',

