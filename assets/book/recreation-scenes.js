'float bird(vec2 q, float t, float s){ float f=sin(t*7.)*.35; vec2 a=vec2(abs(q.x),q.y);',
'  float w=sdSeg(a,vec2(0.),vec2(.035,.012+f*.02)*s); w=min(w,sdSeg(a,vec2(.035,.012+f*.02)*s,vec2(.06,-.004+f*.035)*s)); return w; }',

// I: show me how You give life to the dead; a flat line that learns to beat
'vec3 sPulse(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float life=smoothstep(.15,.75,m), x=p.x*2.5+t*.9;',
'  float ph=fract(x*.5), beat=exp(-sq((ph-.5)*40.))*.16-exp(-sq((ph-.53)*45.))*.07+exp(-sq((ph-.3)*18.))*.02;',
'  float y=beat*life;',
'  float d=abs(p.y-y);',
'  float fade=smoothstep(-.45,-.1,p.x)*(1.-smoothstep(.3,.45,p.x));',
'  c+=vec3(.95)*glowLine(d,1.4*PX)*fade+vec3(.5)*glowLine(d,8.*PX)*fade*.15;',
'  float peace=smoothstep(.75,1.,m);',
'  c+=mix(vec3(1.),WARM,.45)*exp(-length(p-vec2(0.,.17))*20.)*(.3+.7*pow(max(0.,sin(t*2.8)),12.))*peace*.6;',
'  return c; }',

// II and III: four birds, divided over four mountains, return alive when called
'vec3 sBirds(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  for(int k=0;k<4;k++){ float fk=float(k); float cx=-.33+fk*.22;',
'    float h=-.3+.18+.04*sin(fk*2.);',
'    float mt=step(p.y,h-abs(p.x-cx)*1.5)*step(-.3,p.y);',
'    c=mix(c,vec3(.035)+vec3(.05)*fbm(p*14.),mt*step(abs(p.x-cx),.13));',
'    c+=vec3(.6)*glowLine(p.y-(h-abs(p.x-cx)*1.5),1.2*PX)*step(abs(p.x-cx),.12)*step(-.3,p.y); }',
'  float split=smoothstep(.0,.4,m), back=smoothstep(.55,.95,m);',
'  for(int k=0;k<4;k++){ float fk=float(k); float cx=-.33+fk*.22, h=-.12+.04*sin(fk*2.);',
'    vec2 home=vec2(cx,h+.03), center=vec2(cos(t*.8+fk*1.57),sin(t*.8+fk*1.57)*.4)*.08+vec2(0.,.18);',
'    vec2 start=vec2((fk-1.5)*.03,.18);',
'    vec2 pos=mix(mix(start,home,split),center,back);',
'    float d=bird(p-pos,t+fk,1.);',
'    c+=vec3(.95)*glowLine(d,1.3*PX)*(.35+.65*max(back,1.-split*.6)); }',
'  return c; }',

// IV: the forces of the soul, four beams that reunite through a prism
'vec3 sForces(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  vec2 v0=vec2(-.1,-.09), v1=vec2(.1,-.09), v2=vec2(0.,.09);',
'  float e=min(min(sdSeg(p,v0,v1),sdSeg(p,v1,v2)),sdSeg(p,v2,v0));',
'  vec2 E=vec2(-.05,0.);',
'  float join=smoothstep(.1,.8,m);',
'  for(int k=0;k<4;k++){ float fk=float(k); vec2 S=vec2(-.6,(fk-1.5)*mix(.16,.02,join));',
'    float sh=.45+fk*.15;',
'    c+=vec3(sh)*glowLine(sdSeg(p,S,E),1.3*PX)*(.5+.5*sin(t*2.+fk)*.3); }',
'  vec2 X=vec2(.06,0.);',
'  c+=vec3(1.)*glowLine(sdSeg(p,X,X+vec2(.7,0.)),mix(.6,1.8,join)*PX)*join+vec3(.5)*glowLine(sdSeg(p,X,X+vec2(.7,0.)),9.*PX)*join*.2;',
'  c+=vec3(.05)*step(e,.0)+vec3(.85)*glowLine(e,1.3*PX);',
'  return c; }',

// V: to create from within certainty, not from doubt and not from imitation
'vec3 sCertain(vec2 p, float t, float m){',
'  vec3 c=bg(p,t); float r=length(p), a=atan(p.y,p.x);',
'  float sure=smoothstep(.1,.8,m);',
'  float shake=(1.-sure)*(.03*(fbm(vec2(a*6.,t*1.5))-.5)+.02*sin(a*23.+t*9.));',
'  float R=.2*(.75+.25*cos(3.*a+t*.15))+shake;',
'  float drawn=step(mod(-a+PI*.5+6.2832,6.2832)/6.2832,mix(.3,1.,sure)+.001);',
'  c+=vec3(.95)*glowLine(r-R,mix(1.,1.5,sure)*PX)*mix(.5,1.,sure)*mix(1.,drawn,sure*0.)+vec3(.4)*glowLine(r-R,9.*PX)*sure*.15;',
'  c+=vec3(.25)*glowLine(r-R*1.06-(1.-sure)*.02*sin(a*7.-t),1.*PX)*(1.-sure);',
'  c+=mix(vec3(1.),WARM,.3)*pt(p,vec2(0.),.00004)*sure;',
'  return c; }',

// VI: "Be, and it is"; a wave of possibility collapses into one point and a form crystallises
'vec3 sBe(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.7; float r=length(p);',
'  float col=smoothstep(.2,.5,m), form=smoothstep(.55,.95,m);',
'  float spread=mix(.32,.0,col);',
'  float wave=pow(.5+.5*cos(r*55.-t*3.),3.)*exp(-r*r/(spread*spread+.0001))*(1.-col);',
'  c+=vec3(.6)*wave;',
'  c+=vec3(1.)*exp(-r*mix(30.,12.,glowLine(m-.5,.05)))*glowLine(m-.5,.05)*1.2;',
'  vec2 q=rot(t*.1)*p; float hx=max(abs(q.x)*.866+abs(q.y)*.5,abs(q.y))-.16*form;',
'  vec2 q2=rot(.5236)*q; float hx2=max(abs(q2.x)*.866+abs(q2.y)*.5,abs(q2.y))-.1*form;',
'  c+=vec3(.95)*glowLine(hx,1.4*PX)*form+vec3(.6)*glowLine(hx2,1.1*PX)*form;',
'  c+=vec3(.08)*step(hx,0.)*form+vec3(1.)*pt(p,vec2(0.),.00004)*(col);',
'  return c; }',

// VII: faith as small as a mustard seed, and the mountain moves
'vec3 sSeed(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float mv=smoothstep(.15,.95,m)*.42;',
'  float x=p.x-.05-mv;',
'  float h=-.3+max(0.,.34-abs(x)*1.2)+.04*fbm(vec2(x*8.,1.));',
'  float mt=step(p.y,h)*step(-.3,p.y);',
'  c=mix(c,vec3(.04)+vec3(.07)*fbm(vec2(x,p.y)*12.),mt);',
'  c+=vec3(.8)*glowLine(p.y-h,1.4*PX)*step(-.3,p.y)*step(-.3,h);',
'  for(int k=1;k<5;k++){ float fk=float(k); float tr=h; float xx=p.x-.05-mv+fk*.02*smoothstep(.0,.2,mv); }',
'  c+=vec3(.5)*glowLine(p.y+.3,1.*PX)*step(abs(p.x),.6);',
