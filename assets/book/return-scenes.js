// Black & White Universe, chapter 10 «Return to the Drop»: the scenes the shared engine (bwu-scene.js) renders.
// The water drop from chapter 1 returns here; at the end it glows from within: the same drop, now conscious.
window.BWU_SCENES = [
'vec3 bg(vec2 p, float t){ return vec3(.01)+vec3(.03)*fbm(p*2.2+vec2(t*.02,-t*.015))*(1.-smoothstep(0.,1.2,length(p)))+vec3(stars(p*55.,.03))*.35; }',
'vec3 WARM=vec3(1.,.62,.34);',
'float pt(vec2 p, vec2 c, float k){ vec2 d=p-c; return k/(dot(d,d)+k); }',
'float sdDrop(vec3 q, float t){',
'  q.y+=.05; float w=1.-.78*smoothstep(-.05,.62,q.y);',
'  float d=length(vec3(q.x/w*1.12,q.y*.92,q.z/w*1.12))-.46;',
'  d+=.005*sin(q.y*14.+t*2.2)*sin(atan(q.z,q.x)*3.+t);',
'  return d*w*.75; }',
'vec3 dropN(vec3 p, float t){ vec2 e=vec2(.002,0.);',
'  return normalize(vec3(sdDrop(p+e.xyy,t)-sdDrop(p-e.xyy,t), sdDrop(p+e.yxy,t)-sdDrop(p-e.yxy,t), sdDrop(p+e.yyx,t)-sdDrop(p-e.yyx,t))); }',
'vec3 studio(vec3 d){',
'  float soft=smoothstep(.55,.95,d.y)*(1.-smoothstep(.2,.6,abs(d.x)));',
'  float side=smoothstep(.6,.95,d.x)*(1.-smoothstep(.1,.5,abs(d.y)))*.35;',
'  return vec3(.015+.05*smoothstep(-.2,1.,d.y)+soft*1.6+side); }',
'vec3 ocean(vec3 d, float t){',
'  vec3 sun=normalize(vec3(.3,.16,-1.));',
'  if(d.y>0.){ float sky=.22+.55*pow(1.-d.y,6.); return vec3(sky+pow(max(dot(d,sun),0.),300.)*2.); }',
'  vec2 uv=d.xz/(-d.y+.03); float wv=fbm(uv*1.4+vec2(t*.15,t*.05));',
'  float haze=pow(1.+d.y,10.);',
'  float glint=pow(max(dot(normalize(vec3(d.x,-d.y,d.z)),sun),0.),30.)*smoothstep(.5,.75,wv)*1.6;',
'  return vec3(.04+.22*wv*haze+.35*haze+glint); }',
'vec3 galaxy(vec3 d, float t){',
'  vec2 q=d.xy/(abs(d.z)+.35)*1.7; q=mat2(.8,-.6,.6,.8)*q; q.y*=1.8;',
'  float r=length(q), a=atan(q.y,q.x);',
'  float arms=.5+.5*cos(2.*(a-log(r+.001)*2.4-t*.06));',
'  float g=exp(-r*2.2)*(.25+.75*arms*arms)*(.6+.6*fbm(q*6.+t*.02))+exp(-r*r*60.)*.8;',
'  return vec3(g*1.1+stars(d.xy*60.,.07)*.8+stars(d.yz*90.,.05)*.6); }',
// the drop: inner 0 = ocean, 1 = galaxy; wake 0..1 = asleep to awake (light from within)
'vec3 dropAt(vec2 p, float t, float spin, float inner, float wake, float scale){',
'  p=p/scale*1.35; vec3 c=vec3(0.);',
'  if(length(p)>.62) return vec3(-1.);',
'  float ang=t*.12+spin, ca=cos(ang), sa=sin(ang);',
'  vec3 ro=vec3(0.,0.,2.4), rd=normalize(vec3(p,-1.9));',
'  ro.xz=mat2(ca,-sa,sa,ca)*ro.xz; rd.xz=mat2(ca,-sa,sa,ca)*rd.xz;',
'  float tt=0., hit=0., md=9.; vec3 pos=ro;',
'  for(int i=0;i<64;i++){ pos=ro+rd*tt; float d=sdDrop(pos,t); md=min(md,d); if(d<.0008){ hit=1.; break; } tt+=d; if(tt>4.) break; }',
'  if(hit<.5) return vec3(-1.-exp(-md*45.)*.25);',
'  vec3 n=dropN(pos,t); float th=max(dot(-rd,n),0.), fres=.02+.98*pow(1.-th,5.);',
'  vec3 refl=studio(reflect(rd,n)); vec3 ri=refract(rd,n,1./1.33);',
'  ri.xz=mat2(ca,sa,-sa,ca)*ri.xz; vec3 ex=normalize(vec3(ri.x*2.6,-ri.y*2.6,ri.z));',
'  vec3 ins=inner<.5 ? ocean(ex,t)*(.25+.45*wake) : galaxy(ex,t)*(.3+.35*wake);',
'  ins*=.5+.5*th;',
'  c=mix(ins,refl,fres)+vec3(.55)*pow(1.-th,3.)*.45;',
'  c+=vec3(pow(max(dot(reflect(rd,n),normalize(vec3(-.4,.8,.6))),0.),180.)*2.5);',
'  c+=mix(vec3(1.),WARM,.35)*exp(-dot(pos.xy,pos.xy)*14.)*wake*.35;',
'  return c; }',
'vec3 withDrop(vec3 c, vec2 p, float t, float spin, float inner, float wake, float scale){',
'  vec3 d=dropAt(p,t,spin,inner,wake,scale);',
'  if(d.x<0.) return c+vec3(.25)*max(0.,-d.x-1.);',
'  return d; }',

// I: in the beginning only a drop, a colourless sphere floating in the dark; God said "Be", and it was
'vec3 sAsleep(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.7;',
'  float be=smoothstep(.7,.95,m);',
'  c+=vec3(.5)*glowLine(length(p)-(.05+.4*fract(t*.15))*be,6.*PX)*be*.3;',
'  return withDrop(c,p,t,0.,0.,be*.6,1.); }',

// II: after light and shadow, love and reason, word and silence, breath and number, the universe returns, awake
'vec3 sTurning(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float in_=smoothstep(.0,.85,m);',
'  for(int k=0;k<9;k++){ float fk=float(k); float an=fk*.698+t*.25+in_*4.;',
'    float R=mix(.42,.0,in_)+.02; vec2 P=vec2(cos(an),sin(an))*R;',
'    c+=vec3(1.)*pt(p,P,.00005)*(1.-in_*.8)+vec3(.4)*exp(-length(p-P)*40.)*(1.-in_);',
'    for(int j=1;j<8;j++){ float aj=an-float(j)*.06; float Rj=R+float(j)*.004; c+=vec3(.5)*pt(p,vec2(cos(aj),sin(aj))*Rj,.000006)*(1.-float(j)/8.)*(1.-in_)*2.5; } }',
'  return withDrop(c,p,t,.3,0.,smoothstep(.6,1.,m),.9); }',

// III: we began as a drop in an infinite sea and end as a sea within a single drop
'vec3 sSeaIn(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  return withDrop(c,p,t,.6,0.,.4+.6*smoothstep(.0,.8,m),mix(.9,1.15,smoothstep(0.,1.,m))); }',

// IV: from the drop you came, you became the ocean, and in the end the ocean returns to the drop
'vec3 sReturnOcean(vec2 p, float t, float m){',
'  vec3 c=bg(p,t); float r=length(p);',
'  float outw=smoothstep(.0,.5,m), back=smoothstep(.5,1.,m);',
'  float R=mix(.04,.45,outw)*mix(1.,.0,back);',
'  for(int k=0;k<5;k++){ float fk=float(k); float Rk=R*(1.-fk*.17);',
'    c+=vec3(.8)*glowLine(r-Rk,1.3*PX)*(1.-fk*.18)*step(.01,Rk); }',
'  c+=vec3(.08)*(1.-smoothstep(R-.01,R,r))*outw*(1.-back);',
'  float sc=mix(.35,.0,outw)+mix(0.,.7,back);',
'  if(sc>.02) c=withDrop(c,p,t,1.,0.,back,sc);',
'  return c; }',

// V: singularity, fana; opposites no longer fight, but rest within each other
'vec3 sRest(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.6; float r=length(p), a=atan(p.y,p.x);',
'  float wind=mix(1.,6.,smoothstep(0.,.9,m));',
'  float s=sin(a+log(r+.001)*wind-t*.3*(1.-m));',
'  float white=smoothstep(-.05,.05,s);',
'  float disc=1.-smoothstep(.27,.275,r);',
'  vec3 col=mix(vec3(.03),vec3(.82),white)*disc;',
'  float rest=smoothstep(.75,1.,m);',
'  col=mix(col,vec3(.42)*disc,rest*(1.-smoothstep(.0,.27,r))*.6);',
'  c=mix(c,col,disc); c+=vec3(.7)*glowLine(r-.27,1.3*PX);',
'  c+=mix(vec3(1.),WARM,.3)*pt(p,vec2(0.),.00004)*rest;',
'  return c; }',

// VI: silence, sound, light, awareness, and back to silence; the circle never ends
'vec3 sCircle(vec2 p, float t, float m){',
'  vec3 c=bg(p,t); float r=length(p), a=atan(p.y,p.x);',
'  float R=.22; c+=vec3(.35)*glowLine(r-R,1.*PX);',
'  float head=PI*.5-(t*.35+m*6.2832);',
'  float da=mod(head-a+6.2832,6.2832); c+=vec3(.9)*glowLine(r-R,1.6*PX)*exp(-da*2.);',
'  c+=mix(vec3(1.),WARM,.3)*pt(p,R*vec2(cos(head),sin(head)),.00004);',
'  vec2 S0=vec2(0.,R), S1=vec2(R,0.), S2=vec2(0.,-R), S3=vec2(-R,0.);',
'  c+=vec3(.6)*glowLine(length(p-S0)-.012,1.*PX);',
'  c+=vec3(.6)*glowLine(p.y-.012*sin((p.x-S1.x)*120.),1.*PX)*step(abs(p.x-S1.x-.035),.03)*step(abs(p.y),.03);',
'  c+=vec3(.9)*pt(p,S2,.00004)+vec3(.3)*exp(-length(p-S2)*40.);',
'  vec2 q=p-S3; c+=vec3(.6)*glowLine(abs(q.y)-.012*(1.-sq(q.x/.03)),1.*PX)*step(abs(q.x),.03);',
'  return c; }',

// VII: we never truly die, we only return; each death a doorway to beginning again
'vec3 sDoors(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.6;',
'  float z=fract(t*.12+m*.6);',
'  for(int k=0;k<6;k++){ float fk=float(k); float s=pow(.62,fk-z*1.)*.9;',
'    vec2 q=p/s; float W=.11, H=.17; vec2 qq=q-vec2(0.,-.05);',
'    float arch=qq.y>H-W ? length(qq-vec2(0.,H-W))-W : abs(qq.x)-W;',
'    float vis=step(-.2,qq.y)*(1.-smoothstep(4.,5.5,fk-z));',
'    c+=vec3(.85)*glowLine(arch*s,1.2*PX)*vis*(1.-fk/7.); }',
'  c+=mix(vec3(1.),WARM,.3)*exp(-length(p-vec2(0.,-.01))*25.)*.35;',
'  return c; }',

// VIII: within every drop a galaxy glows quietly; there are no boundaries, only reflections
'vec3 sReflections(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.6;',
'  float open=smoothstep(.3,.95,m);',
'  vec2 g=floor(p*5.+.5), f=p*5.-g; float r=length(f);',
'  float has=step(length(g),2.3);',
'  vec2 q=rot(t*.1+h21(g)*6.)*f*2.4; float gr=length(q), ga=atan(q.y,q.x);',
'  float gal=exp(-gr*2.6)*(.3+.7*sq(.5+.5*cos(2.*(ga-log(gr+.001)*2.4))))+exp(-gr*gr*30.)*.6;',
'  float rim=glowLine(r-.33,.012)*(1.-open);',
'  float inside=1.-smoothstep(.31,.33+open*.4,r);',
'  c+=(vec3(.75)*gal*inside+vec3(.7)*rim)*has;',
'  return c; }',

// IX: every human a mirror of God and every God a spark within man; from Him, in Him, back to Him
'vec3 sMirror(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float meet=smoothstep(.2,.9,m), x=mix(.2,0.,meet);',
'  c+=vec3(.35)*glowLine(p.x,1.*PX)*step(abs(p.y),.3)*(1.-meet);',
'  c+=mix(vec3(1.),WARM,.35)*(pt(p,vec2(-x,0.),.00004)+exp(-length(p-vec2(-x,0.))*25.)*.2);',
'  c+=vec3(.75)*(pt(p,vec2(x,0.),.00003)+exp(-length(p-vec2(x,0.))*25.)*.12);',
'  c+=vec3(.5)*glowLine(length(p)-.1*meet,1.*PX)*meet;',
'  return c; }',

// X and XI: God is here, in the stillness between two breaths; be silent, and let creation continue through you
'vec3 sBetween(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float x=p.x*2.2+t*.25, ph=fract(x);',
'  float breath=ph<.7 ? sin(ph/.7*PI) : 0.;',
'  float fade=smoothstep(-.5,-.2,p.x)*(1.-smoothstep(.35,.5,p.x));',
'  c+=vec3(.8)*glowLine(p.y+.02-.13*breath,1.3*PX)*fade;',
'  float pause=step(.7,ph)*fade;',
'  c+=mix(vec3(1.),WARM,.35)*glowLine(p.y+.02,2.*PX)*pause*smoothstep(.1,.6,m);',
'  float born=smoothstep(.6,1.,m);',
'  vec2 g=floor(p*30.); float spark=step(.93,h21(g+floor(t*.7)))*glowLine(length(fract(p*30.)-.5),.08)*(1.-smoothstep(.15,.4,abs(p.y+.02)))*fade;',
'  c+=vec3(.9)*spark*born;',
'  return c; }',

// XII: in the beginning a drop; in the end the same drop, but now it is conscious
'vec3 sConscious(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  c+=mix(vec3(1.),WARM,.25)*exp(-length(p)*5.)*.12*smoothstep(.3,1.,m);',
'  return withDrop(c,p,t,0.,1.,smoothstep(.0,.9,m),1.); }',

'vec3 scene(float id, vec2 p, float t, float m){',
'  if(id<.5) return sAsleep(p,t,m);',
'  if(id<1.5) return sTurning(p,t,m);',
'  if(id<2.5) return sSeaIn(p,t,m);',
'  if(id<3.5) return sReturnOcean(p,t,m);',
'  if(id<4.5) return sRest(p,t,m);',
'  if(id<5.5) return sCircle(p,t,m);',
'  if(id<6.5) return sDoors(p,t,m);',
'  if(id<7.5) return sReflections(p,t,m);',
'  if(id<8.5) return sMirror(p,t,m);',
'  if(id<9.5) return sBetween(p,t,m);',
'  return sConscious(p,t,m); }'
].join('\n');
