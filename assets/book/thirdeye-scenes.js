// Black & White Universe, chapter 06 «The Third Eye»: the scenes the shared engine (bwu-scene.js) renders.
window.BWU_SCENES = [
'vec3 bg(vec2 p, float t){ return vec3(.01)+vec3(.03)*fbm(p*2.2+vec2(t*.02,-t*.015))*(1.-smoothstep(0.,1.2,length(p)))+vec3(stars(p*55.,.03))*.35; }',
'vec3 WARM=vec3(1.,.62,.34);',
'float pt(vec2 p, vec2 c, float k){ vec2 d=p-c; return k/(dot(d,d)+k); }',
'float lidD(vec2 q, float W, float H){ return abs(q.y)-H*(1.-sq(q.x/W)); }',
'vec3 eye(vec2 q, float W, float open, float glow, float t){',
'  float H=W*.45*open+.0015, lid=lidD(q,W,H), inside=(1.-smoothstep(-.002,.002,lid))*step(abs(q.x),W);',
'  float r=length(q), iris=1.-smoothstep(W*.3,W*.32,r), pupil=1.-smoothstep(W*.11,W*.12,r);',
'  float tex=.35+.65*fbm(vec2(atan(q.y,q.x)*12.,r*30./W));',
'  vec3 c=vec3(.06)*inside; c=mix(c,vec3(.5)*tex*(.4+.6*glow),iris*inside); c=mix(c,vec3(0.),pupil*inside);',
'  c+=mix(vec3(1.),WARM,.3)*glow*exp(-r/W*7.)*inside*.8;',
'  c+=vec3(.85)*glowLine(lid,1.2*PX)*step(abs(q.x),W);',
'  return c; }',

// I: the first eye of darkness, the second that knew itself, the third through which the universe sees
'vec3 sThree(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float o1=smoothstep(.0,.25,m), o2=smoothstep(.3,.55,m), o3=smoothstep(.62,.9,m);',
'  c+=eye(p-vec2(-.17,-.07),.09,o1,0.,t)*.55;',
'  c+=eye(p-vec2(.17,-.07),.09,o2,.3,t)*.8;',
'  vec2 q=rot(PI*.5)*(p-vec2(0.,.13));',
'  c+=eye(q,.085,o3,o3,t);',
'  c+=mix(vec3(1.),WARM,.3)*exp(-length(p-vec2(0.,.13))*14.)*o3*.25;',
'  return c; }',

// II: black and white dissolve into a single light, the seer and the seen become one
'vec3 sDissolve(vec2 p, float t, float m){',
'  float w=mix(.003,.5,smoothstep(0.,.75,m));',
'  float b=.04*sin(p.y*9.+t)*(1.-m);',
'  float side=smoothstep(-w,w,p.x-b);',
'  float mist=.45+.3*fbm(p*3.+t*.05);',
'  vec3 c=mix(vec3(.015),vec3(mist),side);',
'  float one=smoothstep(.55,1.,m);',
'  c=mix(c,vec3(.03),one*.85);',
'  float r=length(p);',
'  c+=mix(vec3(1.),WARM,.2)*(exp(-r*mix(30.,7.,one))*one*.9+pt(p,vec2(0.),.00006)*one);',
'  c+=vec3(.8)*glowLine(p.x-b,1.2*PX)*(1.-smoothstep(.0,.3,m));',
'  c*=1.-smoothstep(.3,.75,r)*(1.-one*.5);',
'  return c; }',

// III: open the eye that rests within your heart
'float heartF(vec2 q){ float x=q.x, y=q.y*1.1, k=x*x+y*y-1.; return k*k*k-x*x*y*y*y; }',
'vec3 sHeartEye(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float beat=1.+.04*pow(max(0.,sin(t*3.)),8.);',
'  vec2 q=p/(.2*beat); q.y-=.12; float e=.004;',
'  float h=heartF(q), hx=heartF(q+vec2(e,0.)), hy=heartF(q+vec2(0.,e));',
'  float d=h/max(length(vec2(hx-h,hy-h))/e,1e-3)*.2;',
'  c+=vec3(.9)*glowLine(d,1.5*PX)+vec3(.35)*glowLine(d,10.*PX)*.25;',
'  c+=vec3(.05)*step(h,0.);',
'  c+=eye(p-vec2(0.,.0),.075,smoothstep(.15,.85,m),smoothstep(.5,1.,m),t);',
'  return c; }',

// IV and V: heaven has always been within us; the gate that does not judge, but forgives
'vec3 sGate(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.7;',
'  float W=.11, H=.17, open=smoothstep(.05,.8,m);',
'  vec2 q=p-vec2(0.,-.05);',
'  float arch=q.y>H-W ? length(q-vec2(0.,H-W))-W : abs(q.x)-W;',
'  float inside=(1.-smoothstep(-.002,.002,arch))*step(-.2,q.y);',
'  float door=step(abs(q.x),W*(1.-open));',
'  vec3 heaven=vec3(.35+.5*exp(-length(q-vec2(0.,.05))*5.))+vec3(.25)*fbm(q*6.+vec2(t*.05,0.));',
'  heaven=mix(heaven,heaven*mix(vec3(1.),WARM,.25),.6);',
'  c=mix(c,mix(heaven,vec3(.04),door),inside);',
'  c+=vec3(.85)*glowLine(arch,1.4*PX)*step(-.2,q.y);',
'  float a=atan(q.x,q.y+.2), rays=pow(.5+.5*cos(a*18.+t*.2),6.)*exp(-length(q)*4.)*step(-.2,q.y);',
'  c+=mix(vec3(1.),WARM,.3)*rays*open*(1.-inside)*.35;',
'  c+=vec3(.6)*glowLine(q.y+.2,1.*PX)*step(abs(q.x),.3);',
'  return c; }',

// VI: the Trinity, three circles that reveal one; seeing, knowing, being
'vec3 sTrinity(vec2 p, float t, float m){',
'  vec3 c=bg(p,t); float R=.13, d=.075;',
'  float one=0.;',
'  for(int k=0;k<3;k++){ float fk=float(k), a=fk*2.0944+PI*.5+t*.08;',
'    float on=smoothstep(fk*.22,fk*.22+.2,m);',
'    vec2 C=vec2(cos(a),sin(a))*d; float r=length(p-C);',
'    c+=vec3(.9)*glowLine(r-R,1.4*PX)*on; one+=step(r,R)*on; }',
'  float all3=step(2.5,one);',
'  c+=mix(vec3(1.),WARM,.3)*(.12*all3+pt(p,vec2(0.),.00004)*smoothstep(.65,.9,m));',
'  c+=vec3(.06)*one;',
'  return c; }',

// VII: the source of light, its reflection in us, and the current of awareness between them
'vec3 sFlow(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.6;',
'  vec2 S=vec2(0.,.2), Rf=vec2(0.,-.2);',
'  c+=mix(vec3(1.),WARM,.3)*(pt(p,S,.00008)+exp(-length(p-S)*14.)*.3);',
'  float wob=.01*sin(p.x*60.+t*2.);',
'  c+=vec3(.6)*(pt(p+vec2(wob,0.),Rf,.00005)+exp(-length(p-Rf)*16.)*.2)*smoothstep(.1,.45,m);',
'  c+=vec3(.25)*glowLine(p.y,1.*PX)*step(abs(p.x),.3);',
'  float stream=glowLine(p.x+.012*sin(p.y*20.-t*2.),.008)*step(abs(p.y),.2);',
'  float dash=pow(.5+.5*sin(p.y*70.-t*5.),4.)*.6+pow(.5+.5*sin(p.y*70.+t*5.+1.),4.)*.6;',
'  c+=vec3(.9)*stream*dash*smoothstep(.4,.75,m);',
'  float know=smoothstep(.8,1.,m); c+=vec3(.4)*glowLine(length(p)-.27,1.*PX)*know;',
'  return c; }',

// VIII: teach us to number our days, a ring of days counted 1, 2, 3 and back to 1
'vec3 sDays(vec2 p, float t, float m){',
'  vec3 c=bg(p,t); float r=length(p), a=atan(p.y,p.x);',
'  float N=30., R=.24, beat=floor(t*1.6);',
'  float idx=floor(mod(-a/6.2832+.25,1.)*N+.5);',
'  float da=abs(fract((-a/6.2832+.25)*N+.5)-.5)/N*6.2832*R;',
'  float three=mod(idx,3.)+1.;',
'  float cur=mod(beat,N), lit=step(idx,cur)*smoothstep(.0,.3,m);',
'  float pulse=glowLine(idx-cur,.6);',
'  float sz=mix(1.3,2.6,three/3.)*PX;',
'  c+=vec3(1.)*glowLine(da,sz)*glowLine(r-R,sz)*(.25+.6*lit+pulse);',
'  float back=smoothstep(.55,1.,m);',
'  c+=vec3(.5)*glowLine(r-R*(1.-back*.92),1.2*PX)*back*.6;',
'  c+=mix(vec3(1.),WARM,.3)*pt(p,vec2(0.),.00004)*back;',
'  return c; }',

// IX: the Three that become One, the eye no longer seeing but being seen
'vec3 sSeen(vec2 p, float t, float m){',
'  vec3 c=bg(p,t);',
'  float mg=smoothstep(.05,.6,m);',
'  for(int k=0;k<3;k++){ float a=float(k)*2.0944+t*.3*(1.-mg)+PI*.5; vec2 C=vec2(cos(a),sin(a))*.16*(1.-mg);',
'    c+=vec3(1.)*pt(p,C,.00004)*(1.-smoothstep(.55,.7,m)); }',
'  float seen=smoothstep(.55,.95,m), r=length(p), a=atan(p.y,p.x);',
'  float rays=pow(.5+.5*cos(a*24.),10.)*smoothstep(.1,.16,r)*(1.-smoothstep(.2,.48,r));',
'  float inflow=.5+.5*sin(r*60.+t*4.);',
'  c+=vec3(.75)*rays*inflow*seen;',
'  c+=eye(p,.085,seen,seen,t)*seen;',
'  return c; }',

// X: light returns to its source; darkness learns it always carried the seed of radiance
'vec3 sReturn(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.7; float r=length(p), a=atan(p.y,p.x);',
'  float streak=pow(noise(vec2(a*30.,1.)),6.)*2.;',
'  float flow=fract(r*3.+t*.4);',
'  c+=vec3(.8)*streak*smoothstep(.0,.2,flow)*(1.-flow)*smoothstep(.06,.12,r)*(1.-smoothstep(.3,.5,r))*(.3+.7*m);',
'  float dark=1.-smoothstep(.055,.06,r); c*=1.-dark;',
'  float seed=smoothstep(.35,1.,m);',
'  c+=mix(vec3(1.),WARM,.35)*(pt(p,vec2(0.),.00003)*(.3+.7*seed)+exp(-r*30.)*.4*seed)*(1.-dark*.0);',
'  c+=vec3(.6)*glowLine(r-.06,1.2*PX);',
'  return c; }',

// XI: everything is forgiven, the cracks fill with light and heal into one surface
'vec3 sForgive(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.6; float r=length(p);',
'  float disc=1.-smoothstep(.27,.275,r);',
'  vec2 g=floor(p*9.), f=fract(p*9.); float d1=8., d2=8.;',
'  for(int j=-1;j<=1;j++) for(int i=-1;i<=1;i++){ vec2 b=vec2(float(i),float(j)); vec2 o=vec2(h21(g+b),h21(g+b+5.3)); vec2 rr=b+o-f; float d=dot(rr,rr); if(d<d1){ d2=d1; d1=d; } else if(d<d2){ d2=d; } }',
'  float crack=sqrt(d2)-sqrt(d1);',
'  float fill=smoothstep(.1,.6,m), heal=smoothstep(.7,1.,m);',
'  float line=glowLine(crack,.035)*(1.-heal);',
'  vec3 surf=vec3(.1+.08*fbm(p*10.))+vec3(.45)*heal*exp(-r*4.);',
'  vec3 crackCol=mix(vec3(0.),mix(vec3(1.),WARM,.45),fill);',
'  c=mix(c,surf,disc); c=mix(c,crackCol,line*disc);',
'  c+=vec3(.8)*glowLine(r-.27,1.3*PX)+mix(vec3(1.),WARM,.2)*exp(-r*7.)*heal*.4;',
'  return c; }',

'vec3 scene(float id, vec2 p, float t, float m){',
'  if(id<.5) return sThree(p,t,m);',
'  if(id<1.5) return sDissolve(p,t,m);',
'  if(id<2.5) return sHeartEye(p,t,m);',
'  if(id<3.5) return sGate(p,t,m);',
'  if(id<4.5) return sTrinity(p,t,m);',
'  if(id<5.5) return sFlow(p,t,m);',
'  if(id<6.5) return sDays(p,t,m);',
'  if(id<7.5) return sSeen(p,t,m);',
'  if(id<8.5) return sReturn(p,t,m);',
'  return sForgive(p,t,m); }'
].join('\n');
