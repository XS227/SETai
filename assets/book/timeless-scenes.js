// Black & White Universe, chapter 03 «The Timeless Point»: the scenes the shared engine (bwu-scene.js) renders.
window.BWU_SCENES = [
'vec3 bg(vec2 p, float t){ return vec3(.01)+vec3(.03)*fbm(p*2.2+vec2(t*.02,-t*.015))*(1.-smoothstep(0.,1.2,length(p)))+vec3(stars(p*55.,.035))*.4; }',
'vec3 WARM=vec3(1.,.62,.34);',

// I: the point where time dies, space bends into the singularity and time slows near it; then light is born again
'vec3 sWell(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*.7; float r=length(p), a=atan(p.y,p.x);',
'  float s=mix(.05,.13,m); vec2 q=p*(1.+s/(r+.012));',
'  vec2 g=abs(fract(q*6.)-.5); float grid=glowLine(min(g.x,g.y),.025);',
'  c+=vec3(.5)*grid*smoothstep(.05,.14,r)*(1.-smoothstep(.35,.8,r));',
'  for(int k=0;k<4;k++){ float rk=.1+float(k)*.075, w=1.2*rk;',
'    float dash=step(.55,fract(a/6.2832*36.-t*w*.4));',
'    c+=vec3(.7)*glowLine(r-rk,1.2*PX)*dash*(1.-smoothstep(.3,.42,rk)); }',
'  float hor=1.-smoothstep(.045,.05,r); c*=1.-hor; c+=vec3(.85)*glowLine(r-.05,1.5*PX);',
'  float born=smoothstep(.62,.95,m);',
'  c+=mix(vec3(1.),WARM,.35)*(.00005/(r*r+.00005))*born+WARM*exp(-r*22.)*.18*born;',
'  return c; }',

// II: energy cannot be destroyed, matter dissolves into rings of light that gather into a star again
'vec3 sEnergy(vec2 p, float t, float m){',
'  vec3 c=bg(p,t); float r=length(p);',
'  float thr=-.15+m*2.2, n=fbm(p*14.+3.);',
'  float body=step(r,.12)*smoothstep(thr,thr+.04,n);',
'  float edge=step(r,.12)*glowLine(n-thr,.03)*step(.02,m)*(1.-smoothstep(.45,.55,m));',
'  c+=vec3(.55)*body*(.6+.4*fbm(p*30.))+vec3(1.)*edge*.9;',
'  for(int k=0;k<3;k++){ float fk=float(k);',
'    float out_=clamp((m-.15-fk*.05)/.45,0.,1.), back=clamp((m-.6)/.35,0.,1.);',
'    float rr=mix(.12,.42,out_)*(1.-back)+.002;',
'    float on=smoothstep(0.,.1,out_)*(1.-smoothstep(.85,1.,back));',
'    c+=vec3(.9)*glowLine(r-rr,(1.4+fk*.6)*PX)*on*(1.-fk*.25)+vec3(.4)*glowLine(r-rr,8.*PX)*on*.12; }',
'  float star=smoothstep(.85,1.,m);',
'  c+=vec3(.00006/(r*r+.00006))*star+vec3(.6)*exp(-r*18.)*.2*star;',
'  return c; }',

// III: from "I" to the One, the border of the self widens until it holds everything
'vec3 sSelf(vec2 p, float t, float m){',
'  vec3 c=bg(p,t); float r=length(p);',
'  float R=mix(.045,.75,smoothstep(.15,1.,m));',
'  vec2 g=floor(p*14.); vec2 o=vec2(h21(g),h21(g+3.7))*.8+.1; float d=length(fract(p*14.)-o)/14.;',
'  float pts=glowLine(d,1.6*PX)*step(.35,h21(g+9.));',
'  float inside=1.-smoothstep(R-.02,R+.02,r);',
'  c+=vec3(.3)*pts*(1.-inside)+vec3(1.)*pts*inside*(.6+.4*sin(t*2.+h21(g)*6.));',
'  c+=vec3(.9)*glowLine(r-R,1.5*PX)*(1.-smoothstep(.45,.75,R))+vec3(.35)*glowLine(r-R,10.*PX)*.15;',
'  c+=vec3(.00004/(r*r+.00004))+vec3(.15)*inside*exp(-r*3.);',
'  return c; }',

// IV: the womb of existence, light spirals in; from the seed inside, roots of light grow out
'vec3 sSeed(vec2 p, float t, float m){',
'  vec3 c=bg(p,t); float r=length(p), a=atan(p.y,p.x);',
'  float fall=1.-smoothstep(.35,.6,m);',
'  float arms=pow(.5+.5*cos(3.*(a+log(r+.001)*2.2+t*.5)),14.);',
'  c+=vec3(.8)*arms*fall*smoothstep(.1,.16,r)*(1.-smoothstep(.25,.5,r));',
'  float hole=1.-smoothstep(.095,.1,r); c*=1.-hole*(1.-smoothstep(.4,.7,m)*.0);',
'  c+=vec3(.75)*glowLine(r-.1,1.4*PX)*(1.-smoothstep(.55,.9,m)*.6);',
'  float grow=.02+.42*smoothstep(.4,1.,m);',
'  float f=fbm(vec2(a*2.6,log(r+.001)*1.6-t*.03)), f2=fbm(vec2(a*5.3+2.,log(r+.001)*2.4));',
'  float ridge=pow(1.-abs(f*2.-1.),18.)+.6*pow(1.-abs(f2*2.-1.),24.);',
'  float roots=ridge*(1.-smoothstep(grow-.04,grow,r))*smoothstep(.0,.03,r);',
'  c+=mix(vec3(1.),WARM,.25)*roots*.9;',
'  c+=mix(vec3(1.),WARM,.4)*(.00003/(r*r+.00003))*smoothstep(.3,.5,m);',
'  return c; }',

// V: turning inward, sound fades, the waves turn inward, and a light emerges from within
'vec3 sInward(vec2 p, float t, float m){',
'  vec3 c=bg(p,t)*(1.-.5*smoothstep(.3,.6,m)); float r=length(p);',
'  float outA=1.-smoothstep(.25,.42,m), inA=smoothstep(.35,.5,m)*(1.-smoothstep(.68,.82,m));',
'  float env=1.-smoothstep(.15,.6,r);',
'  float wo=glowLine(abs(fract(r*7.-t*.35)-.5)/7.,1.6*PX), wi=glowLine(abs(fract(r*7.+t*.5)-.5)/7.,1.6*PX);',
'  c+=vec3(.75)*(wo*outA+wi*inA)*env;',
'  float glow=smoothstep(.65,1.,m), a=atan(p.y,p.x);',
'  float rays=pow(noise(vec2(a*7.,t*.2))*.6+.4,3.)*exp(-r*5.);',
'  c+=mix(vec3(1.),WARM,.3)*(exp(-r*14.)*.7+rays*.35+.00004/(r*r+.00004))*glow;',
'  return c; }',

// VI: in the darkness of the night the star shines
'vec3 sStar(vec2 p, float t, float m){',
'  vec3 c=vec3(.006)+vec3(stars(p*70.,.03))*.5*(1.-.5*m)+vec3(stars(p*35.+7.,.02))*.35; float r=length(p);',
'  float b=.25+.75*smoothstep(.1,.8,m), tw=.85+.15*sin(t*5.)*sin(t*3.3);',
'  float spikes=exp(-abs(p.x)*900.)*exp(-abs(p.y)*7.)+exp(-abs(p.y)*900.)*exp(-abs(p.x)*7.);',
'  vec2 q=rot(PI*.25)*p; spikes+=.4*(exp(-abs(q.x)*1400.)*exp(-abs(q.y)*14.)+exp(-abs(q.y)*1400.)*exp(-abs(q.x)*14.));',
'  c+=vec3(1.)*((.00006/(r*r+.00005))+spikes*.7+exp(-r*12.)*.12)*b*tw;',
'  return c; }',

// VII: all moments become one, every ring keeps its own time until they all stand still in one line
'vec3 sTimeless(vec2 p, float t, float m){',
'  vec3 c=bg(p,t); float r=length(p), a=atan(p.y,p.x);',
'  float al=smoothstep(.2,.92,m);',
'  for(int k=0;k<9;k++){ float fk=float(k), rk=.06+fk*.034;',
'    float ang=mix(h21(vec2(fk,2.))*6.2832+t*(.25+fk*.13)*(1.-al), PI*.5, al);',
'    vec2 mk=rk*vec2(cos(ang),sin(ang));',
'    c+=vec3(.22)*glowLine(r-rk,1.*PX)*(1.-al*.7);',
'    c+=vec3(1.)*(.00002/(dot(p-mk,p-mk)+.00002));',
'    float da=mod(ang-a+6.2832,6.2832); c+=vec3(.5)*glowLine(r-rk,1.6*PX)*exp(-da*3.)*(1.-al); }',
'  float one=smoothstep(.85,1.,m);',
'  c+=vec3(1.)*glowLine(p.x,1.6*PX)*step(0.,p.y)*step(p.y,.34)*al*.6+vec3(.00006/(r*r+.00006))*one;',
'  return c; }',

// VIII: a mirror gazing back at the soul, the black hole opens like an eye
'vec3 sMirror(vec2 p, float t, float m){',
'  float r=length(p), a=atan(p.y,p.x);',
'  vec2 lp=p*(1.+.025/(r*r+.001));',
'  vec3 c=vec3(.008)+vec3(stars(lp*50.,.05))*.7;',
'  c+=vec3(1.)*glowLine(r-.125,1.6*PX)+vec3(.6)*exp(-sq((r-.135)*30.))*.3;',
'  float sh=1.-smoothstep(.115,.12,r); c*=1.-sh;',
'  float eye=smoothstep(.25,.85,m);',
'  float iris=(.35+.65*fbm(vec2(a*14.,r*9.)))*smoothstep(.035,.05,r)*(1.-smoothstep(.1,.118,r));',
'  float streak=pow(fbm(vec2(a*40.,r*3.)),2.);',
'  vec3 inner=vec3(stars(-p*50.,.05))*.25+vec3(.55)*iris*streak*1.6+vec3(.3)*iris*.4;',
'  inner+=vec3(.9)*exp(-length(p-vec2(-.03,.04))*90.)*.6;',
'  c+=inner*sh*eye;',
'  return c; }',

// IX: collapse and a new order, the grid falls inward, flashes, and rises again as a sunflower spiral
'vec3 sCollapse(vec2 p, float t, float m){',
'  vec3 c=bg(p,t); float r=length(p);',
'  float col=smoothstep(0.,.45,m), s=1.-col*.94, th=col*2.4;',
'  vec2 g=rot(-th)*p/s; vec2 cell=(floor(g*16.)+.5)/16.;',
'  float d=length(g-cell)*s, keep=step(length(cell),.42);',
'  c+=vec3(.85)*glowLine(d,1.5*PX)*keep*(1.-smoothstep(.42,.5,m))*(.4+.6*col);',
'  c+=vec3(1.)*exp(-r*mix(40.,10.,glowLine(m-.48,.04)))*glowLine(m-.48,.04);',
'  float grow=smoothstep(.5,1.,m), N=320.*grow, cc=.0175, dm=9.;',
'  float i0=floor(pow(r/cc,2.));',
'  for(int j=-24;j<=24;j++){ float i=i0+float(j); if(i<1.||i>N) continue;',
'    float an=i*2.39996+t*.05; vec2 q=cc*sqrt(i)*vec2(cos(an),sin(an)); dm=min(dm,length(p-q)); }',
'  c+=vec3(.95)*glowLine(dm,1.8*PX)*step(.5,m);',
'  return c; }',

// X: darkness realises it has always been carrying the light
'vec3 sRebirth(vec2 p, float t, float m){',
'  float r=length(p);',
'  vec2 lp=p*(1.+.02/(r*r+.001));',
'  vec3 c=vec3(.008)+vec3(stars(lp*50.,.05))*.6;',
'  vec2 q=vec2(p.x,p.y/.24); float qr=length(q), a=atan(q.y,q.x);',
'  float disc=smoothstep(.14,.18,qr)*(1.-smoothstep(.3,.55,qr))*(.3+.8*fbm(vec2(a*3.+t*.35-qr*4.,qr*6.)));',
'  float sh=1.-smoothstep(.105,.11,r);',
'  c+=vec3(.9)*glowLine(r-.113,1.4*PX)*(1.+m);',
'  c*=1.-sh;',
'  float light=smoothstep(.2,1.,m);',
'  vec3 inner=mix(vec3(1.),WARM,.3)*(exp(-r/(.012+light*.06))*1.2*light+.00004/(r*r+.00004)*smoothstep(.05,.3,m));',
'  c+=inner*sh;',
'  c+=vec3(.85)*disc*max(step(p.y,0.),step(.11,r))*(1.-light*.4);',
'  return c; }',

'vec3 scene(float id, vec2 p, float t, float m){',
'  if(id<.5) return sWell(p,t,m);',
'  if(id<1.5) return sEnergy(p,t,m);',
'  if(id<2.5) return sSelf(p,t,m);',
'  if(id<3.5) return sSeed(p,t,m);',
'  if(id<4.5) return sInward(p,t,m);',
'  if(id<5.5) return sStar(p,t,m);',
'  if(id<6.5) return sTimeless(p,t,m);',
'  if(id<7.5) return sMirror(p,t,m);',
'  if(id<8.5) return sCollapse(p,t,m);',
'  return sRebirth(p,t,m); }'
].join('\n');
